# Builds _screenshots/contact-sheet.html: every candidate shot, grouped by
# program, with checkboxes to pick shots and a star to mark the main one.
# "Save picks" downloads picks.json; scripts/apply-picks.py turns that into
# WebP images in img/<id>/ and fills in programs.json.
#
# Usage:  python scripts/make-contact-sheet.py

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHOTS = ROOT / "_screenshots"
EXTS = {".png", ".jpg", ".jpeg", ".webp", ".gif"}


def main():
    data = json.loads((ROOT / "programs.json").read_text(encoding="utf-8"))
    sections, missing = [], []
    for p in data["programs"]:
        folder = SHOTS / p["id"]
        files = sorted(f for f in folder.iterdir() if f.suffix.lower() in EXTS) if folder.exists() else []
        clips = sorted(folder.glob("*.mp4")) if folder.exists() else []
        if not files:
            missing.append(p["name"])
            continue
        tiles = "\n".join(
            f'''<figure class="tile" data-file="{html.escape(f.name)}">
  <img src="{html.escape(p['id'])}/{html.escape(f.name)}" loading="lazy" alt="">
  <figcaption>
    <label><input type="checkbox" class="pick"> Use</label>
    <button type="button" class="star" title="Make this the main shot">★ Main</button>
    <span class="name">{html.escape(f.name)}</span>
  </figcaption>
</figure>''' for f in files)
        clip_html = "".join(
            f'''<figure class="tile clip"><video src="{html.escape(p['id'])}/{html.escape(c.name)}" autoplay muted loop playsinline></video>
  <figcaption><span class="name">Card video (plays automatically on the card): {html.escape(c.name)}</span></figcaption></figure>'''
            for c in clips)
        tiles = clip_html + tiles
        sections.append(f'''<section class="prog" data-id="{html.escape(p['id'])}">
  <h2>{html.escape(p['name'])} <small>{len(files)} shot(s)</small></h2>
  <div class="grid">{tiles}</div>
</section>''')

    missing_html = "".join(f"<li>{html.escape(n)}</li>" for n in missing)
    page = TEMPLATE.replace("{{SECTIONS}}", "\n".join(sections)).replace("{{MISSING}}", missing_html)
    out = SHOTS / "contact-sheet.html"
    out.write_text(page, encoding="utf-8")
    print(f"Wrote {out} ({len(sections)} programs with shots, {len(missing)} without)")


